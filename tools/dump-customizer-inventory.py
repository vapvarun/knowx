#!/usr/bin/env python3
"""Lists every Kirki customizer field: id, type, section, default, output/transport and where it is read.

Run from the theme root: python3 tools/dump-customizer-inventory.py > docs/customizer-inventory.md
Only needed while the Kirki-based fields exist; W07/W08 adapt it to the in-house framework.
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIELDS = sorted((ROOT / 'inc' / 'Kirki_Option' / 'Fields').glob('*.php'))
COMPONENT = (ROOT / 'inc' / 'Kirki_Option' / 'Component.php').read_text()


def match_paren(text, start):
    depth = 0
    for i in range(start, len(text)):
        if text[i] == '(':
            depth += 1
        elif text[i] == ')':
            depth -= 1
            if depth == 0:
                return i
    raise ValueError('unbalanced')


def sections():
    out = {}
    for m in re.finditer(r"new \\Kirki\\Section\(\s*'([^']+)',\s*array\((.*?)\n\t\t\t\)", COMPONENT, re.S):
        title = re.search(r"'title'\s*=>\s*esc_html__\(\s*'([^']*)'", m.group(2))
        out[m.group(1)] = title.group(1) if title else m.group(1)
    return out


def scalar(block, key):
    m = re.search(r"'%s'\s*=>\s*(?:esc_html__\(\s*)?('(?:[^'\\]|\\.)*'|\d+|true|false|array\()" % key, block)
    if not m:
        return ''
    v = m.group(1)
    return 'array(...)' if v == 'array(' else v.strip("'")


def reads(setting):
    r = subprocess.run(['git', 'grep', '-n', '-F', "'%s'" % setting, '--', '*.php', '*.js', ':!inc/Kirki_Option/Fields', ':!audit', ':!plans'], cwd=ROOT, capture_output=True, text=True)
    return [l.split(':')[0] + ':' + l.split(':')[1] for l in r.stdout.splitlines() if 'assets/js/' not in l or '.min.' not in l]


secs = sections()
rows = []
for f in FIELDS:
    text = f.read_text()
    for m in re.finditer(r"new \\Kirki\\Field\\(\w+)\(\s*array\(", text):
        end = match_paren(text, m.end() - 1)
        block = text[m.end():end]
        sid = scalar(block, 'settings')
        rows.append({
            'id': sid,
            'type': m.group(1),
            'section': secs.get(scalar(block, 'section'), scalar(block, 'section')),
            'file': f.name,
            'default': scalar(block, 'default'),
            'output': 'output' in block,
            'transport': scalar(block, 'transport') or '-',
            'active': 'active_callback' in block,
        })

real = [r for r in rows if r['type'] != 'Custom']
print('# Customizer inventory (Kirki fields)\n')
print('Generated by `tools/dump-customizer-inventory.py`. %d fields, %d settings, %d dividers.\n' % (len(rows), len(real), len(rows) - len(real)))
print('| Setting | Type | Section | Default | Output CSS | Transport | Read in |')
print('|---|---|---|---|---|---|---|')
unread = []
for r in real:
    rd = reads(r['id'])
    if not rd and not r['output']:
        unread.append(r['id'])
    if rd:
        where = ', '.join(sorted(set(rd))[:4]) + (' ...' if len(set(rd)) > 4 else '')
    else:
        where = 'Kirki output CSS only' if r['output'] else '**never read**'
    d = r['default'].replace('|', '/')[:30]
    print('| `%s` | %s | %s | %s | %s | %s | %s |' % (r['id'], r['type'], r['section'], d or '-', 'yes' if r['output'] else '-', r['transport'], where))
print('\nSettings with no reader and no output CSS: %s' % (', '.join('`%s`' % u for u in unread) or 'none'))
